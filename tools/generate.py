#!/usr/bin/env python3
"""Generate the zz_generated_*.go files from the shared API files. Standard library only.

    python3 tools/generate.py          write the generated code
    python3 tools/generate.py --check  fail if the generated code is stale

Go needs one package to be importable as one, so generated files sit beside the
hand-written ones and carry the standard "Code generated" marker.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED_DIRS = (ROOT / "shared", ROOT.parent / "shared")
SHARED = next((p for p in SHARED_DIRS if p.exists()), None)
if SHARED is None:
    sys.exit(f"No shared directory at {SHARED_DIRS[0]} or {SHARED_DIRS[1]}. It holds the API files this code is generated from.")
SHARED = SHARED / "api"
HEADER = "// Code generated by tools/generate.py from the shared API files. DO NOT EDIT.\n\n"
SCALARS = {"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}
INITIALISMS = {"id", "url", "api", "http", "https", "uri", "mac", "ip", "ua", "html", "cpu", "cms", "csv", "json", "sql", "tls"}
# Names the hand-written runtime already uses in the package.
RESERVED = {"Client", "Page", "List", "ListResult", "Envelope", "Option", "PageMeta", "ResponseInfo", "Nullable", "FieldError"}


def words(name: str) -> list[str]:
    spaced = re.sub(r"(?<=[a-z0-9])([A-Z])", r" \1", name)
    return [w for w in re.split(r"[_\-. ]+", spaced) if w]


def exported(name: str) -> str:
    parts = [w.upper() if w.lower() in INITIALISMS else w[:1].upper() + w[1:] for w in words(name)]
    text = "".join(parts)
    return "X" + text if text[:1].isdigit() else text


def unexported(name: str) -> str:
    parts = words(name)
    head = parts[0].lower()
    return head + "".join(w.upper() if w.lower() in INITIALISMS else w[:1].upper() + w[1:] for w in parts[1:])


def type_name(name: str) -> str:
    text = exported(name)
    return text + "Object" if text in RESERVED else text


def comment(text: str | None, indent: str = "", prefix: str = "") -> str:
    paragraphs = [re.sub(r"\s+", " ", p).strip() for p in re.split(r"\n\s*\n", text or "") if p.strip()]
    if not paragraphs:
        return ""
    if prefix:
        paragraphs[0] = f"{prefix} {paragraphs[0]}"
    blocks = [
        textwrap.fill(p, 88, initial_indent=f"{indent}// ", subsequent_indent=f"{indent}// ", break_long_words=False, break_on_hyphens=False)
        for p in paragraphs
    ]
    return f"\n{indent}//\n".join(blocks) + "\n"


class Types:
    """Emits one struct per object schema and one string type per named enum."""

    def __init__(self, schemas: dict) -> None:
        self.schemas = schemas
        self.done: set[str] = set()
        self.out: dict[str, str] = {}
        self.returned: set[str] = set()

    def resolve(self, schema: dict) -> dict:
        while "$ref" in schema:
            schema = self.schemas[schema["$ref"].rsplit("/", 1)[-1]]
        return schema

    def unwrap(self, schema: dict) -> tuple[dict, bool]:
        nullable = False
        options = schema.get("oneOf") or schema.get("anyOf")
        if options:
            real = [o for o in options if o.get("type") != "null"]
            nullable = len(real) != len(options)
            schema = real[0] if len(real) == 1 else {}
        if len(schema.get("allOf", [])) == 1:
            schema = schema["allOf"][0]
        kind = schema.get("type")
        if isinstance(kind, list):
            nullable = nullable or "null" in kind
            real_kinds = [k for k in kind if k != "null"]
            schema = {**schema, "type": real_kinds[0] if len(real_kinds) == 1 else None}
        return schema, nullable

    def go_type(self, schema: dict, context: str) -> tuple[str, bool]:
        """(Go type without any pointer, whether null is allowed)."""
        schema, nullable = self.unwrap(schema)
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            target = self.resolve(schema)
            inner, inner_nullable = self.unwrap(target)
            if inner.get("type") == "object" and inner.get("properties"):
                self.emit_struct(type_name(name), inner)
                return type_name(name), nullable or inner_nullable
            if inner.get("enum"):
                self.emit_enum(type_name(name), inner)
                return type_name(name), nullable or inner_nullable
            text, more = self.go_type(inner, context)
            return text, nullable or more or inner_nullable
        kind = schema.get("type")
        if kind == "array":
            inner, _ = self.go_type(schema.get("items", {}), context + "Item")
            return f"[]{inner}", nullable
        if kind == "object":
            if schema.get("properties"):
                self.emit_struct(context, schema)
                return context, nullable
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                inner, _ = self.go_type(extra, context + "Value")
                return f"map[string]{inner}", nullable
            return "map[string]any", nullable
        return SCALARS.get(kind, "any"), nullable

    def field(self, name: str, schema: dict, owner: str, required: bool, body: bool) -> str:
        text, nullable = self.go_type(schema, owner + exported(name))
        collection = text.startswith(("[]", "map[")) or text == "any"
        tag = name
        if body and not required:
            # Left out is different from sent empty or sent null.
            kind = f"*Nullable[{text}]" if nullable else f"*{text}"
            tag += ",omitempty"
        elif body:
            kind = f"*{text}" if nullable and not collection else text
        elif collection:
            kind = text
        else:
            kind = f"*{text}" if nullable or not required else text
        notes = schema.get("description") or ""
        enum = self.unwrap(self.resolve(self.unwrap(schema)[0]))[0].get("enum")
        if enum and "$ref" not in self.unwrap(schema)[0]:
            values = ", ".join(str(v) for v in enum if v is not None)
            notes = f"{notes} One of: {values}. New values may appear.".strip()
        go_name = exported(name)
        return comment(notes, "\t", go_name) + f'\t{go_name} {kind} `json:"{tag}"`\n'

    def emit_struct(self, name: str, schema: dict, body: bool = False) -> None:
        if name in self.done:
            return
        self.done.add(name)
        required = set(schema.get("required", []))
        fields = "".join(self.field(k, v, name, k in required, body) for k, v in schema.get("properties", {}).items())
        self.out[name] = comment(schema.get("description"), "", name) + f"type {name} struct {{\n{fields}}}\n"

    def emit_enum(self, name: str, schema: dict) -> None:
        if name in self.done:
            return
        self.done.add(name)
        constants = "".join(
            f'\t{name}{exported(str(v))} {name} = "{v}"\n' for v in schema["enum"] if isinstance(v, str)
        )
        doc = comment(schema.get("description"), "", name) or f"// {name} is a value from the API. New values may appear.\n"
        self.out[name] = f"{doc}type {name} string\n\nconst (\n{constants})\n"

    def mark_returned(self, name: str) -> None:
        self.returned.add(name)

    def render(self, package: str) -> str:
        setters = "".join(
            f"\nfunc (x *{n}) setResponse(info *ResponseInfo) {{ x.LastResponse = info }}\n" for n in sorted(self.returned)
        )
        body = "\n".join(self.out[n] for n in sorted(self.out))
        for n in sorted(self.returned):
            body = re.sub(
                rf"(type {n} struct \{{\n)",
                "\\1\t// LastResponse holds the HTTP details of the response behind this result.\n"
                '\tLastResponse *ResponseInfo `json:"-"`\n\n',
                body,
                count=1,
            )
        return f"{HEADER}package {package}\n\n{body}{setters}"


class Services:
    def __init__(self, contract: dict, operations: list[dict], types: Types) -> None:
        self.contract = contract
        self.operations = operations
        self.types = types
        self.params: list[str] = []

    def query_parameter(self, op: dict, name: str) -> dict:
        item = self.contract["paths"][op["path"]]
        for parameter in item[op["http_method"].lower()].get("parameters", []) + item.get("parameters", []):
            if "$ref" in parameter:
                parameter = self.contract["components"]["parameters"][parameter["$ref"].rsplit("/", 1)[-1]]
            if parameter["name"] == name:
                return parameter
        raise KeyError(name)

    def params_struct(self, op: dict, name: str, cursor_field: bool) -> str:
        fields, setters = [], []
        for query in op["query_params"]:
            wire = query["name"]
            parameter = self.query_parameter(op, wire)
            schema, _ = self.types.unwrap(self.types.resolve(parameter.get("schema", {})))
            kind = schema.get("type")
            go_name = exported(wire)
            notes = parameter.get("description") or ""
            values = schema.get("enum")
            if values:
                notes = f"{notes} One of: {', '.join(str(v) for v in values if v is not None)}.".strip()
            if kind == "boolean":
                fields.append(comment(notes, "\t", go_name) + f"\t{go_name} *bool\n")
                setters.append(f'\tif p.{go_name} != nil {{\n\t\tq.Set("{wire}", strconv.FormatBool(*p.{go_name}))\n\t}}\n')
            elif kind == "integer":
                fields.append(comment(notes, "\t", go_name) + f"\t{go_name} int\n")
                setters.append(f'\tif p.{go_name} != 0 {{\n\t\tq.Set("{wire}", strconv.Itoa(p.{go_name}))\n\t}}\n')
            else:
                fields.append(comment(notes, "\t", go_name) + f"\t{go_name} string\n")
                setters.append(f'\tif p.{go_name} != "" {{\n\t\tq.Set("{wire}", p.{go_name})\n\t}}\n')
        self.params.append(
            f"// {name} holds the query for this call. Zero values are left out.\n"
            f"type {name} struct {{\n{''.join(fields)}}}\n\n"
            f"func (p *{name}) query() url.Values {{\n\tq := url.Values{{}}\n\tif p == nil {{\n\t\treturn q\n\t}}\n{''.join(setters)}\treturn q\n}}\n"
        )
        return name

    def body_type(self, op: dict, prefix: str) -> str | None:
        body = self.contract["paths"][op["path"]][op["http_method"].lower()].get("requestBody")
        if not body:
            return None
        schema = body["content"]["application/json"]["schema"]
        name = type_name(schema["$ref"].rsplit("/", 1)[-1]) if "$ref" in schema else prefix + "Params"
        self.types.emit_struct(name, self.types.resolve(schema), body=True)
        return name

    def method(self, op: dict, service: str, prefix: str) -> str:
        go_method = exported(op["method"])
        response = op["response"]
        returns = response["returns"]
        model = response.get("data_schema") or response.get("item_schema")
        go_model = type_name(model) if model else None
        if model:
            self.types.emit_struct(go_model, self.types.schemas[model])

        ids = [unexported(p) for p in op["path_params"]]
        args = ["ctx context.Context", *(f"{i} string" for i in ids)]
        has_query = bool(op["query_params"])
        name_prefix = prefix + go_method
        if has_query:
            args.append(f"params *{self.params_struct(op, name_prefix + 'Query', returns == 'page')}")
        body = self.body_type(op, name_prefix)
        if body:
            args.append(f"body *{body}")
        args.append("opts ...Option")

        fields = [f'method: "{op["http_method"]}"', f"retrySafe: {str(op['retry_safe']).lower()}", f"earlyAccess: {str(op['available_in_early_access']).lower()}"]
        if op["idempotency_key"]:
            fields.append("keyed: true")
        lines = []
        if ids:
            pairs = ", ".join(f'"{p}", {i}' for p, i in zip(op["path_params"], ids))
            lines.append(f'\tpath, err := expandPath("{op["path"]}", {pairs})\n')
            fail = {"page": None, "void": "\t\treturn err\n"}.get(returns, "\t\treturn nil, err\n")
            if fail is None:
                lines.append(f"\tif err != nil {{\n\t\treturn failedList[{go_model}](err)\n\t}}\n")
            else:
                lines.append(f"\tif err != nil {{\n{fail}\t}}\n")
            fields.insert(1, "path: path")
        else:
            fields.insert(1, f'path: "{op["path"]}"')
        if has_query:
            fields.append("query: params.query()")
        lines.append(f"\treq := request{{{', '.join(fields)}}}\n")
        if body:
            lines.append("\tif body != nil {\n\t\treq.body = body\n\t}\n")

        if returns == "void":
            result, tail = "error", "\treturn callVoid(ctx, s.client, req, opts)\n"
        elif returns == "page":
            result = f"*List[{go_model}]"
            start = 'params.startCursor()' if has_query else '""'
            tail = f"\treturn newList[{go_model}](ctx, s.client, req, {start}, opts)\n"
        elif returns == "envelope":
            inner = f"[]{go_model}" if response.get("is_array") else go_model
            result, tail = f"(*Envelope[{inner}], error)", f"\treturn callEnvelope[{inner}](ctx, s.client, req, opts)\n"
        elif response.get("is_array"):
            result, tail = f"(*ListResult[{go_model}], error)", f"\treturn callList[{go_model}](ctx, s.client, req, opts)\n"
        else:
            self.types.mark_returned(go_model)
            result, tail = f"(*{go_model}, error)", f"\treturn callData[{go_model}](ctx, s.client, req, opts)\n"

        doc = op.get("summary") or ""
        if not op["available_in_early_access"]:
            doc += "\n\nNot yet available during early access: the API may answer with a 404."
        if op["idempotency_key"]:
            doc += "\n\nSafe to retry: every attempt carries one Idempotency-Key, generated unless you pass WithIdempotencyKey."
        return (
            "\n" + comment(doc, "", f"{go_method}:")
            + f"func (s *{service}) {go_method}({', '.join(args)}) {result} {{\n{''.join(lines)}{tail}}}\n"
        )

    def tree(self) -> dict:
        root: dict = {"children": {}, "operations": []}
        for op in self.operations:
            node = root
            for part in op["resource"]:
                node = node["children"].setdefault(part, {"children": {}, "operations": []})
            node["operations"].append(op)
        return root

    def classes(self, node: dict, chain: list[str]) -> list[str]:
        out: list[str] = []
        for name, child in node["children"].items():
            out += self.classes(child, [*chain, name])
        service = "".join(exported(p) for p in chain) + "Service"
        kids = [(exported(n), "".join(exported(p) for p in [*chain, n]) + "Service") for n in node["children"]]
        fields = "".join(f"\t{a} *{k}\n" for a, k in kids)
        inits = "".join(f"\t\t{a}: new{k}(c),\n" for a, k in kids)
        if not chain:
            out.append(
                f"type services struct {{\n{fields}}}\n\nfunc newServices(c *Client) services {{\n\treturn services{{\n{inits}\t}}\n}}\n"
            )
            return out
        path = ".".join(chain)
        text = (
            f"// {service} is the {path} resource.\ntype {service} struct {{\n\tclient *Client\n{fields}}}\n\n"
            f"func new{service}(c *Client) *{service} {{\n\treturn &{service}{{\n\t\tclient: c,\n{inits}\t}}\n}}\n"
        )
        prefix = "".join(exported(p) for p in chain)
        for op in node["operations"]:
            text += self.method(op, service, prefix)
        out.append(text)
        return out

    def render(self, api_version: str) -> str:
        classes = self.classes(self.tree(), [])
        code = "\n".join(classes)
        params = "\n".join(self.params)
        imports = ['"context"']
        if "url.Values" in params:
            imports.append('"net/url"')
        if "strconv." in params:
            imports.append('"strconv"')
        joined = "\n".join(f"\t{i}" for i in imports)
        start = "".join(
            f"\nfunc (p *{n}) startCursor() string {{\n\tif p == nil {{\n\t\treturn \"\"\n\t}}\n\treturn p.Cursor\n}}\n"
            for n in re.findall(r"type (\w+) struct \{[^}]*\n\tCursor string", params)
        )
        return (
            f"{HEADER}package vojo\n\nimport (\n{joined}\n)\n\n"
            f"// APIVersion is the Vojo-Version this release was built against. It is sent on\n// every request; change it with WithVersion.\n"
            f'const APIVersion = "{api_version}"\n\n{code}\n{params}{start}'
        )


def gofmt(text: str) -> str:
    with tempfile.NamedTemporaryFile("w", suffix=".go", delete=False) as handle:
        handle.write(text)
    path = Path(handle.name)
    try:
        subprocess.run(["gofmt", "-w", str(path)], check=True)
        return path.read_text()
    finally:
        path.unlink()


def build() -> dict[str, str]:
    contract = json.loads((SHARED / "vojo-api.public.json").read_text())
    webhooks = json.loads((SHARED / "vojo-webhooks.public.json").read_text())
    manifest = json.loads((SHARED / "operations.json").read_text())

    types = Types(contract["components"]["schemas"])
    services = Services(contract, manifest["operations"], types).render(manifest["api_version"])

    events = Types(webhooks["components"]["schemas"])
    constants = []
    for event in manifest["events"]:
        name = type_name(event["schema"])
        events.emit_struct(name, events.schemas[event["schema"]])
        constants.append(f'\t// Type{exported(event["type"])} is a {event["type"]} event, decoded as {name}.\n\tType{exported(event["type"])} = "{event["type"]}"\n')
    event_code = events.render("webhook") + f"\nconst (\n{''.join(constants)})\n"

    return {
        "zz_generated_models.go": gofmt(types.render("vojo")),
        "zz_generated_services.go": gofmt(services),
        "webhook/zz_generated_events.go": gofmt(event_code),
    }


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        stale = [n for n, text in files.items() if not (ROOT / n).exists() or (ROOT / n).read_text() != text]
        if stale:
            print(f"Generated code is stale ({', '.join(stale)}). Run: python3 tools/generate.py", file=sys.stderr)
            return 1
        print("Generated code is up to date.")
        return 0
    for name, text in files.items():
        (ROOT / name).write_text(text)
    print(f"Wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
